<h1>🚤 Fishing Boat Management System</h1>

<p>
The Fishing Boat Management System is a web-based application developed to simplify and automate
the management of fishing boats and related activities. The system helps boat owners,
administrators and crew members maintain records digitally instead of using manual registers.
It provides a centralized platform for managing boats, crew members, fishing trips,
catch records, maintenance schedules, sales, expenses and financial reports.
The application improves efficiency, minimizes paperwork, reduces data redundancy and
provides quick access to important information through a simple dashboard.
</p>

<h2>Project Objectives</h2>

<ul>

<li>To maintain complete information about fishing boats.</li>

<li>To manage crew member details and their assigned boats.</li>

<li>To record fishing trips and catch details.</li>

<li>To maintain maintenance records for every boat.</li>

<li>To record fish sales and customer details.</li>

<li>To manage operational expenses.</li>

<li>To automatically calculate Profit and Loss.</li>

<li>To generate reports for better decision making.</li>

<li>To provide secure login with Admin and Crew roles.</li>

</ul>

